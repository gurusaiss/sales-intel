import type { CIQReport } from "./companyIntelStore";

/** Port of CompanyIQ's markdown_generator.py — generates a full markdown document from a CIQReport */
export function generateMarkdown(companyName: string, report: CIQReport): string {
  const lines: string[] = [];
  const now = new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" });

  lines.push(`# ${companyName} — Company Intelligence Report`);
  lines.push(`*Generated ${now} by Sales Intelligence Platform*`);
  lines.push("");
  lines.push("---");
  lines.push("");

  // Table of contents
  lines.push("## Table of Contents");
  const sections = [
    "Company Overview", "Founders & Leadership", "Origin Story & Timeline",
    "Past Challenges", "Current Products & Projects", "Roadmap & Future Direction",
    "Competitive Landscape", "Ongoing Struggles", "Interview Preparation",
    "Culture & Work Environment", "Red Flags", "Application Strategy", "Candidate Fit",
  ];
  sections.forEach((s, i) => {
    const anchor = s.toLowerCase().replace(/[^a-z0-9]+/g, "-");
    lines.push(`${i + 1}. [${s}](#${anchor})`);
  });
  lines.push("");
  lines.push("---");
  lines.push("");

  function section(title: string, content?: string) {
    if (!content) return;
    lines.push(`## ${title}`);
    lines.push("");
    lines.push(content.trim());
    lines.push("");
    lines.push("---");
    lines.push("");
  }

  section("Company Overview", report.overview);
  section("Founders & Leadership", report.founders);
  section("Origin Story & Timeline", report.originStory);
  section("Past Challenges", report.challenges);
  section("Current Products & Projects", report.productsProjects);
  section("Roadmap & Future Direction", report.roadmap);
  section("Competitive Landscape", report.competitive);
  section("Ongoing Struggles", report.struggles);

  // Interview questions as numbered list
  if (report.interviewQuestions?.length) {
    lines.push("## Interview Preparation");
    lines.push("");
    lines.push("Likely interview questions for this company:");
    lines.push("");
    report.interviewQuestions.forEach((q, i) => {
      lines.push(`${i + 1}. ${q}`);
    });
    lines.push("");
    lines.push("---");
    lines.push("");
  }

  section("Culture & Work Environment", report.culture);
  section("Red Flags", report.redFlags);
  section("Application Strategy", report.applicationStrategy);
  section("Candidate Fit", report.candidateFit);

  if (report.raw && !report.overview) {
    lines.push("## Raw Analysis");
    lines.push("");
    lines.push(report.raw);
    lines.push("");
  }

  lines.push(`*Report generated by Sales Intelligence Platform — ${now}*`);
  return lines.join("\n");
}
